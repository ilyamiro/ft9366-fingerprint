#!/usr/bin/env python3
"""Generate ft9366_script.h from a tshark field dump of a recorded session.

The device protocol (bulk OUT 0x01 / bulk IN 0x82, 4-8 byte commands) is replayed from
three recorded slices: INIT (reset + chip bring-up), IDLE (one wake + finger-detect cycle,
whose last reply is the interrupt flag) and SCAN (finger-down branch incl. image read).

Encoding: repeated [op:1][len:2 BE][payload]; op 0 = bulk write payload, 1 = bulk read
len bytes, 2 = delay len milliseconds.
usage: gen_script.py DUMP.txt OUT.h
"""
import sys

dump, out = sys.argv[1], sys.argv[2]
ev = []
for line in open(dump):
    f = line.rstrip('\n').split('|')
    urb, tt, ep = f[2].strip("'"), f[3], f[4]
    data = bytes.fromhex(f[11]) if len(f) > 11 and f[11] else b''
    if tt != '0x03':
        continue
    t = float(f[1])
    if ep == '0x01' and urb == 'S':
        ev.append((t, 'OUT', data))
    elif ep == '0x82' and urb == 'C':
        ev.append((t, 'IN', data))

SLICES = {
    'init': (0, 296),
    'idle': (2922, 2986),
    'scan': (3250, 3309),
}

def encode(a, b):
    buf = bytearray(); prev = ev[a][0]
    for i in range(a, b):
        t, d, data = ev[i]
        gap_ms = int(round(min(t - prev, 0.2) * 1000))
        if gap_ms >= 3 and i != a:
            buf += bytes([2]) + gap_ms.to_bytes(2, 'big')
        prev = t
        if d == 'OUT':
            buf += bytes([0]) + len(data).to_bytes(2, 'big') + data
        else:
            buf += bytes([1]) + len(data).to_bytes(2, 'big')
    return bytes(buf)

with open(out, 'w') as fh:
    fh.write("/* Generated by gen_script.py from a recorded session. Do not edit by hand. */\n")
    fh.write("#pragma once\n\n")
    for name, (a, b) in SLICES.items():
        blob = encode(a, b)
        fh.write(f"static const guint8 ft9366_{name}_script[] = {{\n")
        for k in range(0, len(blob), 16):
            fh.write("  " + ", ".join(f"0x{x:02x}" for x in blob[k:k+16]) + ",\n")
        fh.write("};\n\n")
print("wrote", out)
