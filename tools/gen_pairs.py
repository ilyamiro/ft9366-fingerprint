import numpy as np
rng = np.random.default_rng(12345)
pairs = np.array([rng.choice(45, 2, replace=False) for _ in range(256)])
with open('ft9366_pairs.h', 'w') as f:
    f.write("/* Sample-pair table for the 256-bit keypoint descriptor (generated by gen_pairs.py). */\n")
    f.write("static const unsigned char FT9366_PAIRS[256][2] = {\n")
    for i in range(0, 256, 8):
        f.write("  " + " ".join("{%d,%d}," % (a, b) for a, b in pairs[i:i + 8]) + "\n")
    f.write("};\n")
