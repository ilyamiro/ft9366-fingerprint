#!/usr/bin/env python3
"""Generate ft9366_script.h (the init / idle / scan command tables).

The device protocol (bulk OUT 0x01 / bulk IN 0x82, 3-24 byte commands) is replayed from three
slices recorded from the reader's USB traffic: INIT (reset + chip bring-up), IDLE (one wake +
finger-detect cycle, whose last reply is the interrupt flag) and SCAN (finger-down branch
including the image read).

Each step is a bulk write, a bulk read of N bytes, or a delay in milliseconds.  Writes are
annotated with what the command does, using the command set described in docs/PROTOCOL.md.

usage: gen_script.py DUMP.txt OUT.h        (DUMP.txt: tshark field dump of a recorded session)
"""
import sys

SLICES = {
    'init': (0, 296),
    'idle': (2922, 2986),
    'scan': (3250, 3309),
}


def load_events(dump):
    ev = []
    for line in open(dump):
        f = line.rstrip('\n').split('|')
        urb, tt, ep = f[2].strip("'"), f[3], f[4]
        data = bytes.fromhex(f[11]) if len(f) > 11 and f[11] else b''
        if tt != '0x03':
            continue
        t = float(f[1])
        if ep == '0x01' and urb == 'S':
            ev.append((t, 'OUT', data))
        elif ep == '0x82' and urb == 'C':
            ev.append((t, 'IN', data))
    return ev


def to_steps(ev, a, b):
    """Turn recorded events a..b into [('W', bytes) | ('R', len) | ('D', ms)]."""
    steps = []
    prev = ev[a][0]
    for i in range(a, b):
        t, d, data = ev[i]
        gap_ms = int(round(min(t - prev, 0.2) * 1000))
        if gap_ms >= 3 and i != a:
            steps.append(('D', gap_ms))
        prev = t
        steps.append(('W', data) if d == 'OUT' else ('R', len(data)))
    return steps


def describe(d):
    """One-line meaning of a command written to the bridge, or '' if not understood."""
    if len(d) == 4 and d[0] == 0x4c and d[1] == 0x5a:
        return 'bridge sync, mode %d' % d[2]
    if d[:4] == bytes([0x44, 0x80, 0, 0]):
        return 'sensor reset'
    if len(d) == 4 and d[0] == 0x09:
        return 'write bridge reg 0x%02x%02x = 0x%02x' % (d[1], d[2], d[3])
    if len(d) == 5 and d[0] == 0x08:
        return 'read bridge reg 0x%02x%02x' % (d[1], d[2])
    if len(d) >= 8 and d[0] == 0x05 and d[1] == 0xfa:
        n = d[5]
        words = ' '.join('%02x%02x' % (d[6 + 2 * k], d[7 + 2 * k]) for k in range(n))
        return 'write %d sensor reg(s) from 0x%02x%02x: %s' % (n, d[2], d[3], words)
    if len(d) >= 6 and d[0] == 0x04 and d[1] == 0xfb:
        return 'read %d sensor reg(s) from 0x%02x%02x' % (d[5], d[2], d[3])
    if len(d) >= 6 and d[0] == 0x06 and d[1] == 0xf9:
        return 'read %d words from FIFO 0x%02x%02x' % ((d[4] << 8) | d[5], d[2], d[3])
    if d[:2] == bytes([0x5a, 0xa5]):
        return 'enter sensor transaction'
    if d[:2] == bytes([0xa5, 0x5a]):
        return 'leave sensor transaction'
    if d and d[0] in (0xc0, 0xc2, 0xc4):
        return 'bridge command 0x%02x' % d[0]
    return ''


def emit(steps, out):
    with open(out, 'w') as fh:
        fh.write("/* Generated by tools/gen_script.py from a recorded session. Do not edit by hand. */\n")
        fh.write("#pragma once\n\n")
        for name, st in steps.items():
            fh.write("static const Ft9366Step ft9366_%s_script[] = {\n" % name)
            for kind, v in st:
                if kind == 'W':
                    note = describe(v)
                    fh.write("  FT9366_WRITE (%s),%s\n" % (
                        ', '.join('0x%02x' % x for x in v),
                        ('  /* %s */' % note) if note else ''))
                elif kind == 'R':
                    fh.write("  FT9366_READ (%d),\n" % v)
                else:
                    fh.write("  FT9366_DELAY (%d),\n" % v)
            fh.write("};\n\n")


if __name__ == '__main__':
    dump, out = sys.argv[1], sys.argv[2]
    ev = load_events(dump)
    emit({n: to_steps(ev, a, b) for n, (a, b) in SLICES.items()}, out)
    print("wrote", out)
